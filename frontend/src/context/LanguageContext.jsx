export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem('binmar_lang') || 'en';
    } catch {
      return 'en';
    }
  });

  const setLang = (newLang) => {
    const valid = newLang === 'ar' ? 'ar' : 'en';
    setLangState(valid);
    try {
      localStorage.setItem('binmar_lang', valid);
    } catch {}
    document.documentElement.dir = valid === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = valid;
  };

  useEffect(() => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, replacements = {}) => {
    const dict = translations[lang] || translations.en;
    let text = dict[key] || translations.en[key] || key;
    if (replacements && typeof replacements === 'object') {
      Object.entries(replacements).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      });
    }
    return text;
  };

  const tCountry = (countryName) => {
    if (!countryName) return '';
    const match = COUNTRY_NAME_MAP[countryName];
    if (match) {
      return match[lang] || match.en || countryName;
    }
    return countryName;
  };

  const isRTL = lang === 'ar';

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tCountry, isRTL }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: 'en',
      setLang: () => {},
      t: (key) => translations.en[key] || key,
      tCountry: (c) => c,
      isRTL: false
    };
  }
  return ctx;
}
